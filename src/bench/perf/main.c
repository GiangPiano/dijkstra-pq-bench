/**
 * Bench1: Microarchitectural Hardware Profiling Runner for Dijkstra Heaps
 * Designed to work with Linux `perf stat` hardware counters.
 */

#include <fcntl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#include "../dijkstra.h"
#include "../graph.h"
#include "../ubench.h"

UBENCH_STATE();

extern const Graph* g_perf_sparse;
extern const Graph* g_perf_dense;

static void notify_perf_ctl(int ctl_fd, int ack_fd, const char* cmd) {
  if (ctl_fd < 0) return;
  dprintf(ctl_fd, "%s\n", cmd);
  if (ack_fd >= 0) {
    char buf[32];
    ssize_t n = read(ack_fd, buf, sizeof(buf) - 1);
    (void)n;
  }
}

int main(int argc, char* argv[]) {
  if (argc < 3) {
    fprintf(stderr, "Usage: %s <sparse|dense> <decrease_key|lazy> [iterations]\n", argv[0]);
    fprintf(stderr, "Configurations:\n");
    fprintf(stderr, "  sparse: N=50,000, d=4   (M=200,000)\n");
    fprintf(stderr, "  dense:  N=50,000, d=128 (M=6,400,000)\n");
    return 1;
  }

  const char* config_name = argv[1];
  const char* mode_name   = argv[2];

  int default_iters = 1;
  if (strcmp(config_name, "sparse") == 0) {
    default_iters = 5;
  } else if (strcmp(config_name, "dense") == 0) {
    default_iters = 1;
  } else {
    fprintf(stderr, "[ERROR] Unknown config: %s (expected 'sparse' or 'dense')\n", config_name);
    return 1;
  }

  int iterations = (argc >= 4) ? atoi(argv[3]) : default_iters;
  if (iterations <= 0) iterations = 1;

  void (*dijkstra_fn)(int*, const Graph*) = NULL;
  if (strcmp(mode_name, "decrease_key") == 0) {
    dijkstra_fn = dijkstra_decrease_key;
  } else if (strcmp(mode_name, "lazy") == 0) {
    dijkstra_fn = dijkstra_lazy;
  } else {
    fprintf(stderr, "[ERROR] Unknown mode: %s (expected 'decrease_key' or 'lazy')\n", mode_name);
    return 1;
  }

  // 1. Reference the graph generated by gen.py
  const Graph* g = (strcmp(config_name, "sparse") == 0) ? g_perf_sparse : g_perf_dense;
  if (!g) {
    fprintf(stderr, "[ERROR] Graph '%s' is NULL. Ensure data/src/perf_%s.c is generated and linked.\n",
            config_name, config_name);
    return 1;
  }

  int* dist = (int*)malloc(sizeof(int) * g->num_vertices);
  if (!dist) {
    fprintf(stderr, "[ERROR] Failed to allocate dist array\n");
    return 1;
  }

  // 2. Open optional perf control FIFO
  const char* ctl_path = getenv("PERF_CTL_FIFO");
  const char* ack_path = getenv("PERF_ACK_FIFO");
  int ctl_fd = -1;
  int ack_fd = -1;

  if (ctl_path && ack_path) {
    ctl_fd = open(ctl_path, O_WRONLY);
    ack_fd = open(ack_path, O_RDONLY);
  }

  // 3. Warm-up pass (outside of perf measurement)
  dijkstra_fn(dist, g);

  // 4. Enable perf measurement
  notify_perf_ctl(ctl_fd, ack_fd, "enable");

  // 5. Target benchmark loop
  for (int iter = 0; iter < iterations; iter++) {
    dijkstra_fn(dist, g);
  }

  // 6. Disable perf measurement immediately
  notify_perf_ctl(ctl_fd, ack_fd, "disable");

  if (ctl_fd >= 0) close(ctl_fd);
  if (ack_fd >= 0) close(ack_fd);

  free(dist);

  return 0;
}
